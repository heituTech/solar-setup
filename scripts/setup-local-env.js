'use strict';

// Generates local development credentials for the four microservices:
//  - RSA key pair used by identity to sign JWTs (keys/)
//  - one .env per service (services/*-service/.env, gitignored)
//  - a ready-to-run MySQL root script (database/local/001_create_services.sql, gitignored)
//  - the seeded super admin credentials (database/local/admin-credentials.txt, gitignored)

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
require('dotenv').config();

const root = path.join(__dirname, '..');
const force = process.argv.includes('--force');
const services = [
  { name: 'identity', port: 7101 },
  { name: 'sales', port: 7102 },
  { name: 'delivery', port: 7103 },
  { name: 'finance', port: 7104 },
  // HRMS 不单独建库，直接复用 finance 数据库读取台账数据做业绩统计
  { name: 'hrms', port: 7105, db: 'finance' },
];

function randomSecret(bytes = 24) {
  return crypto.randomBytes(bytes).toString('base64url');
}

function readOrCreateKeys() {
  const dir = path.join(root, 'keys');
  fs.mkdirSync(dir, { recursive: true });
  const privatePath = path.join(dir, 'jwt-private.pem');
  const publicPath = path.join(dir, 'jwt-public.pem');
  if (fs.existsSync(privatePath) && fs.existsSync(publicPath)) {
    return { privateKey: fs.readFileSync(privatePath, 'utf8'), publicKey: fs.readFileSync(publicPath, 'utf8') };
  }
  const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });
  fs.writeFileSync(privatePath, privateKey);
  fs.writeFileSync(publicPath, publicKey);
  return { privateKey, publicKey };
}

function envLine(key, value) {
  return `${key}=${String(value).replace(/\n/g, '\\n')}`;
}

function main() {
  const dbHost = process.env.DB_HOST || '127.0.0.1';
  const dbPort = process.env.DB_PORT || '3306';
  const { privateKey, publicKey } = readOrCreateKeys();
  const internalSecret = randomSecret(32);
  const passwords = {};
  for (const service of services) passwords[service.name] = randomSecret(18);
  const adminEmail = process.env.ADMIN_EMAIL || 'admin@example.com';
  const adminPassword = `Solar-${randomSecret(9)}`;
  const urls = Object.fromEntries(services.map((s) => [s.name, `http://127.0.0.1:${s.port}`]));

  for (const service of services) {
    const file = path.join(root, 'services', `${service.name}-service`, '.env');
    if (fs.existsSync(file) && !force) {
      console.log(`skip existing ${path.relative(root, file)} (use --force to overwrite)`);
      continue;
    }
    const dbName = service.db || service.name;
    const lines = [
      `PORT=${service.port}`,
      `SERVICE_NAME=${service.name}`,
      `DB_HOST=${dbHost}`,
      `DB_PORT=${dbPort}`,
      `DB_USER=solar_${dbName}`,
      `DB_PASSWORD=${passwords[dbName]}`,
      `DB_NAME=solar_${dbName}`,
      `INTERNAL_SERVICE_SECRET=${internalSecret}`,
      `IDENTITY_URL=${urls.identity}`,
      `SALES_URL=${urls.sales}`,
      `DELIVERY_URL=${urls.delivery}`,
      `FINANCE_URL=${urls.finance}`,
    ];
    if (service.name === 'identity') {
      lines.push(envLine('JWT_PRIVATE_KEY', privateKey));
      lines.push(envLine('JWT_PUBLIC_KEY', publicKey));
      lines.push('JWT_EXPIRES_IN=7d');
      lines.push(`ADMIN_EMAIL=${adminEmail}`);
      lines.push(`ADMIN_PASSWORD=${adminPassword}`);
      lines.push(`ADMIN_NAME=Super Admin`);
    } else {
      lines.push(envLine('JWT_PUBLIC_KEY', publicKey));
    }
    fs.writeFileSync(file, `${lines.join('\n')}\n`);
    console.log(`wrote ${path.relative(root, file)}`);
  }

  const sqlDir = path.join(root, 'database', 'local');
  fs.mkdirSync(sqlDir, { recursive: true });
  const sql = [];
  sql.push('-- Generated by scripts/setup-local-env.js');
  sql.push('-- Run as MySQL root: mysql -u root -p < database/local/001_create_services.sql');
  sql.push('-- Contains generated passwords. Never commit this file.');
  sql.push('');
  for (const service of services) {
    if (service.db) continue;
    sql.push(`CREATE DATABASE IF NOT EXISTS solar_${service.name} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`);
    sql.push(`CREATE USER IF NOT EXISTS 'solar_${service.name}'@'%' IDENTIFIED BY '${passwords[service.name]}';`);
    sql.push(`ALTER USER 'solar_${service.name}'@'%' IDENTIFIED BY '${passwords[service.name]}';`);
    sql.push(`GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES ON solar_${service.name}.* TO 'solar_${service.name}'@'%';`);
    sql.push('');
  }
  sql.push('FLUSH PRIVILEGES;');
  fs.writeFileSync(path.join(sqlDir, '001_create_services.sql'), `${sql.join('\n')}\n`);

  fs.writeFileSync(
    path.join(sqlDir, 'admin-credentials.txt'),
    `email: ${adminEmail}\npassword: ${adminPassword}\n`
  );

  console.log('');
  console.log('Next steps:');
  console.log(`1. Run as MySQL root: mysql -h ${dbHost} -P ${dbPort} -u root -p < database/local/001_create_services.sql`);
  console.log('2. npm run migrate');
  console.log('3. npm run seed:admin');
  console.log(`4. npm run dev   (super admin: ${adminEmail})`);
}

main();
